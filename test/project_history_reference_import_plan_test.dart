import 'package:flutter_test/flutter_test.dart';
import 'package:subtitle_studio/database/models/models.dart';
import 'package:subtitle_studio/services/project_document_codec.dart';
import 'package:subtitle_studio/widgets/session_selection/project_history_import_plan.dart';
import 'package:subtitle_studio/widgets/session_selection/project_history_reference_import_plan.dart';

ProjectSubtitleLineData _line() => ProjectSubtitleLineData.create(
  index: 1,
  startTime: '00:00:01,000',
  endTime: '00:00:02,000',
  original: 'Original',
  edited: null,
  marked: false,
  comment: null,
  resolved: false,
);

SubtitleLine _convert(ProjectSubtitleLineData data) => SubtitleLine()
  ..index = data.index
  ..startTime = data.startTime
  ..endTime = data.endTime
  ..original = data.original
  ..edited = data.edited
  ..marked = data.marked
  ..comment = data.comment
  ..resolved = data.resolved;

PreparedProjectHistory _history() => PreparedProjectHistory.build([
  ProjectCheckpointData.create(
    id: 10,
    sessionId: 2,
    subtitleCollectionId: 5,
    timestamp: DateTime.utc(2026, 10, 13).toIso8601String(),
    operationType: 'snapshot',
    description: 'Root',
    parentCheckpointId: null,
    isActive: true,
    checkpointType: 'snapshot',
    metadata: null,
    deltas: const [],
    snapshot: [_line()],
  ),
], toSubtitleLine: _convert);

ProjectHistoryReferencesData _refs(
  int headId, {
  String branchName = 'refs/heads/main',
  int? branchId,
}) => ProjectHistoryReferencesData.create(entries: [
  ProjectHistoryReferenceData(
    name: 'HEAD', kind: 'head', targetCheckpointId: headId,
  ),
  ProjectHistoryReferenceData(
    name: branchName,
    kind: 'branch',
    targetCheckpointId: branchId ?? headId,
  ),
]);

void main() {
  test('valid autogenerated refs and absent section import compatibly', () {
    final history = _history();
    expect(
      ProjectHistoryReferenceImportPlan.prepare(
        data: null, history: history,
      ),
      isNull,
    );
    final plan = ProjectHistoryReferenceImportPlan.prepare(
      data: _refs(10), history: history,
    )!;
    expect(plan.headCheckpointId, 10);
    final mapped = plan.remap(
      destinationSessionId: 99,
      destinationCollectionId: 199,
      idMap: {10: 500},
    );
    expect(mapped.headCheckpointId, 500);
    expect(mapped.references.map((ref) => ref.checkpointId), [500, 500]);
  });

  test('mismatched HEAD ref fails before any import transaction', () {
    expect(
      () => ProjectHistoryReferenceImportPlan.prepare(
        data: _refs(100),
        history: _history(),
      ),
      throwsA(isA<ProjectHistoryImportException>()),
    );
  });

  test('unknown branch name cannot be silently discarded', () {
    expect(
      () => ProjectHistoryReferenceImportPlan.prepare(
        data: _refs(10, branchName: 'refs/heads/my-feature'),
        history: _history(),
      ),
      throwsA(isA<ProjectHistoryImportException>()),
    );
  });

  test('unknown checkpoint targets and extra refs fail closed', () {
    expect(
      () => ProjectHistoryReferenceImportPlan.prepare(
        data: _refs(10, branchId: 999),
        history: _history(),
      ),
      throwsA(isA<ProjectHistoryImportException>()),
    );
  });

  test('ref section without history requires subtitle-only recovery', () {
    expect(
      () => ProjectHistoryReferenceImportPlan.prepare(
        data: _refs(10),
        history: null,
      ),
      throwsA(isA<ProjectHistoryImportException>()),
    );
  });
}
