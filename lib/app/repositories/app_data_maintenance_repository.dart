import 'dart:io';

import 'package:isar_community/isar.dart';
import 'package:path_provider/path_provider.dart';
import 'package:subtitle_studio/database/models/models.dart';
import 'package:subtitle_studio/utils/logging_helpers.dart';

/// Destructive application-maintenance operations.
///
/// Kept outside UI code so Settings never reaches the global database helper
/// directly. Dictionary data is intentionally preserved.
class AppDataMaintenanceRepository {
  final Isar _isar;

  static final _cachedPcmName = RegExp(r'^waveform_audio_\d+_[0-9a-f]{8}\.raw$');
  static final _temporaryPcmName = RegExp(r'^waveform_temp_\d+_\d+\.raw$');

  /// Only these file names are generated by our audio/waveform pipeline.
  static bool isOwnedTemporaryWaveformFile(String name) =>
      _cachedPcmName.hasMatch(name) || _temporaryPcmName.hasMatch(name);

  const AppDataMaintenanceRepository(this._isar);

  Future<void> clearAllApplicationData() async {
    await logInfo(
      'Starting complete data wipe',
      context: 'AppDataMaintenanceRepository.clearAllApplicationData',
    );

    try {
      await clearStoredApplicationData();

      await _deleteWaveformCache();
      await _deleteTemporaryWaveformFiles();

      await logInfo(
        'Data wipe completed successfully',
        context: 'AppDataMaintenanceRepository.clearAllApplicationData',
      );
    } catch (e, stackTrace) {
      await logError(
        'Application data wipe failed',
        error: e,
        stackTrace: stackTrace,
        context: 'AppDataMaintenanceRepository.clearAllApplicationData',
      );
      rethrow;
    }
  }

  /// Clear project and preferences data in one transaction, including the
  /// separate Git-style branch/bookmark ref collection. Dictionary entries
  /// and files outside the app's database are intentionally untouched.
  Future<void> clearStoredApplicationData() async {
    await _isar.writeTxn(() async {
      await _isar.preferences.clear();
      await _isar.sessions.clear();
      await _isar.subtitleCollections.clear();
      await _isar.checkpoints.clear();
      await _isar.historyRefs.clear();
      await _isar.videoPreferences.clear();
      await _isar.tutorialStatus.clear();
    });
  }

  Future<void> _deleteWaveformCache() async {
    try {
      final appDocDir = await getApplicationDocumentsDirectory();
      final waveformDir = Directory('${appDocDir.path}/waveforms');
      if (await waveformDir.exists()) {
        await waveformDir.delete(recursive: true);
      }
    } catch (e, stackTrace) {
      await logWarning(
        'Could not fully clear waveform cache: $e',
        stackTrace: stackTrace,
        context: 'AppDataMaintenanceRepository._deleteWaveformCache',
      );
    }
  }

  Future<void> _deleteTemporaryWaveformFiles() async {
    try {
      final tempDir = await getTemporaryDirectory();
      if (!await tempDir.exists()) return;

      // On desktop the OS temporary directory may be shared by many apps.
      // Never recursively empty it, and never touch imported subtitle files.
      await for (final entity in tempDir.list(followLinks: false)) {
        if (entity is! File) continue;
        final name = entity.uri.pathSegments.last;
        if (!isOwnedTemporaryWaveformFile(name)) continue;
        try {
          await entity.delete();
        } catch (e, stackTrace) {
          await logWarning(
            'Could not delete a temporary waveform file: $e',
            stackTrace: stackTrace,
            context: 'AppDataMaintenanceRepository._deleteTemporaryWaveformFiles',
          );
        }
      }
    } catch (e, stackTrace) {
      await logWarning(
        'Could not fully clear temporary waveform files: $e',
        stackTrace: stackTrace,
        context: 'AppDataMaintenanceRepository._deleteTemporaryWaveformFiles',
      );
    }
  }
}
